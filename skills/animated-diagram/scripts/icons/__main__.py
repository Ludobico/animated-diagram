"""Regenerate references/icons.md from the registry. Run from scripts/:

    python -m icons            # writes ../references/icons.md
    python -m icons out.md
"""
import sys
from pathlib import Path

from icons import ICONS, INFO, _RULES


def keywords(pattern, limit=6):
    # readable hints, not exact regexes: next\.?js -> next.js, load.?balanc -> loadbalanc, logs? -> logs
    words = [w.replace("\\b", "").replace("\\.?", ".").replace(".?", "").replace("?", "").replace("\\.", ".")
             for w in pattern.split("|")]
    return ", ".join(words[:limit]) + (", ..." if len(words) > limit else "")


def render():
    rules = dict(_RULES)
    order = [k for k, _ in _RULES]
    lines = [
        "# Icons",
        "",
        "Generated by `python -m icons` from `scripts/icons/`. Do not edit by hand.",
        "",
        "Set `\"icon\": \"<key>\"` on a node, or leave it out and the key is guessed from the label",
        "and sub-label: the first rule (in the priority order below) whose keyword appears wins.",
        "There is no catch-all icon: when nothing matches, `make_diagram.py` stops and names the node.",
        "Pick a key below or draw one (`custom-icons.md`). Full patterns: `scripts/icons/__init__.py`.",
        "",
        "| key | shape | micro-interaction | auto-selected by (priority) |",
        "|---|---|---|---|",
    ]
    for key in sorted(ICONS, key=lambda k: (order.index(k) if k in order else len(order), k)):
        shape, motion = INFO[key]
        auto = f"{order.index(key) + 1}. {keywords(rules[key])}" if key in rules else "set explicitly"
        lines.append(f"| `{key}` | {shape} | {motion} | {auto} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "references" / "icons.md"
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out} ({len(ICONS)} icons)")
